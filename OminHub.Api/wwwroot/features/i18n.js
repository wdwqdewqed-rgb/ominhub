import { Storage } from "../core/storage.js";

function setupLanguage() {
    const langSelect = document.getElementById("lang-select");
    const currentLang = Storage.getStored("ominhub_lang", "en");

    if (langSelect) {
        langSelect.value = currentLang;

        langSelect.addEventListener("change", async (e) => {
            const newLang = e.target.value;
            console.log(`🌐 Changing language to: ${newLang}`);

            // Guardar preferencia
            setStored("ominhub_lang", newLang);

            // Aplicar traducción a elementos estáticos
            translateUI(newLang);

            // OBTENER la página actual
            const currentPage = getCurrentPageKey();
            console.log(`📄 Current page: ${currentPage}`);

            // Si estamos en una página con contenido dinámico, recargarlo
            if (currentPage === "creators" || currentPage === "about" ||
                currentPage === "studio" || currentPage === "terms" ||
                currentPage === "privacy" || currentPage === "support" ||
                currentPage === "safety") {
                await reloadDynamicPage(currentPage, newLang);
            }

            // Actualizar navegación
            Router.wireNavigation();
        });
    }

    // Aplicar traducción inicial
    translateUI(currentLang);

    // Asegurar que los textos originales se guarden
    setTimeout(() => {
        saveOriginalTexts();
    }, 100);
}

function translateUI(lang) {
    const elements = document.querySelectorAll("[data-translate]");
    const translationMap = translations[lang] || {};

    console.log(`Translating to ${lang}, found ${elements.length} elements`);

    elements.forEach((el) => {
        const key = el.getAttribute("data-translate");

        // Si estamos en inglés (lang === "en"), necesitamos restaurar el texto original
        if (lang === "en") {
            // El texto original está en el contenido HTML inicial
            // Para restaurarlo, podemos usar el dataset para guardar el original
            if (!el.dataset.originalText) {
                // Guardar el texto original si no lo tenemos
                el.dataset.originalText = el.textContent;
                if (el.placeholder !== undefined) {
                    el.dataset.originalPlaceholder = el.placeholder;
                }
            }

            // Restaurar el texto original
            if (el.placeholder !== undefined && el.dataset.originalPlaceholder) {
                el.placeholder = el.dataset.originalPlaceholder;
            } else if (el.textContent) {
                el.textContent = el.dataset.originalText || el.textContent;
            }
        } else {
            // Para otros idiomas, usar la traducción
            const translation = translationMap[key];

            if (translation) {
                // Guardar el texto original si no lo tenemos
                if (!el.dataset.originalText) {
                    el.dataset.originalText = el.textContent;
                    if (el.placeholder !== undefined) {
                        el.dataset.originalPlaceholder = el.placeholder;
                    }
                }

                if (el.placeholder !== undefined) {
                    el.placeholder = translation;
                } else if (el.getAttribute('aria-label')) {
                    el.setAttribute('aria-label', translation);
                } else if (el.title) {
                    el.title = translation;
                } else {
                    el.textContent = translation;
                }
            } else if (lang !== "en") {
                console.warn(`Missing translation for key: "${key}" in ${lang}`);
            }
        }
    });

    // También traducir opciones del dropdown
    const langSelect = document.getElementById("lang-select");
    if (langSelect) {
        const options = langSelect.querySelectorAll("option");
        options.forEach(option => {
            const value = option.value;
            if (value === "en") {
                option.textContent = "English";
            } else if (value === "es") {
                option.textContent = "Español";
            }
        });
    }

    // Actualizar textos dinámicos que no tienen data-translate
    updateDynamicTexts(lang);
}

function updateDynamicTexts(lang) {
    // Actualizar textos que se generan dinámicamente
    const currentYear = new Date().getFullYear();

    // Buscar elementos que contengan el año
    const yearElements = document.querySelectorAll('[data-translate-year]');
    yearElements.forEach(el => {
        if (lang === "es") {
            el.textContent = `© ${currentYear} OMINHUB. Todos los derechos reservados.`;
        } else {
            el.textContent = `© ${currentYear} OMINHUB. All rights reserved.`;
        }
    });
}

